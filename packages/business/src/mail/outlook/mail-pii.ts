// 학습 코퍼스에 남으면 안 되는 것들. 서명부에 휴대폰·주소가 대량으로 붙어 있고
// (검증 결과 트랜스크립트 45개), 유출 시 피해가 사람에게 간다. 값은 지우되 자리는
// 남긴다 — "연락처를 남기는 습관" 자체는 문체 학습에 필요하다.
const RULES: Array<[RegExp, string]> = [
  [/\b01[016-9][-. ]?\d{3,4}[-. ]?\d{4}\b/g, "[휴대폰]"],
  [/\+82[-. ]?10[-. ]?\d{3,4}[-. ]?\d{4}/g, "[휴대폰]"],
  [/\b0\d{1,2}[-. ]\d{3,4}[-. ]\d{4}\b/g, "[전화]"],
  [/\b\d{3}-\d{2}-\d{5}\b/g, "[사업자번호]"],
  [/\b\d{6}-[1-4]\d{6}\b/g, "[주민번호]"],
  [/\b\d{2,3}-\d{2,6}-\d{2,8}\b(?=\s*(계좌|은행))/g, "[계좌]"],
  [/(서울|부산|대구|인천|광주|대전|울산|세종|경기|강원|충북|충남|전북|전남|경북|경남|제주)\s?\S*[시군구]\s\S+(로|길)\s?\d[\d\-길]*[^\n,]{0,20}/g, "[주소]"],
];

export function maskPii(text: string): string {
  return RULES.reduce((acc, [pattern, replacement]) => acc.replace(pattern, replacement), text);
}
