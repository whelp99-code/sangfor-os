/** 프롬프트에 붙일 헌장 텍스트. 헌장이 없는 도메인은 회사 맥락만 준다. */
export function renderCharter(domain: GtmDomain): string {
  const lines = ["[회사 맥락]", ...COMPANY_CONTEXT.map((l) => `  - ${l}`)];

  const charter = DOMAIN_CHARTERS[domain];
  if (charter) {
    lines.push(
      "",
      `[직무] ${charter.mission}`,
      "",
      "[이 일로 판단하는 신호]",
      ...charter.triggers.map((t) => `  - ${t}`),
      "",
      "[표준 절차 — 실제 처리 이력에서 도출]",
      ...charter.procedure.map((p, i) => `  ${i + 1}. ${p}`),
      "",
      "[착수 전 반드시 확보할 정보 — 없으면 만들지 말고 되물어라]",
      ...charter.requiredInputs.map((r) => `  - ${r}`),
      "",
      "[위임·에스컬레이션]",
      ...charter.escalation.map((e) => `  - ${e}`),
      "",
      "[사람이 판단해야 하는 것 — 단독 결정 금지]",
      ...charter.humanOnly.map((h) => `  - ${h}`),
      "",
      `[완료 조건] ${charter.completion}`,
    );
  }

  lines.push("", "[대표 명의로 글을 쓸 때]", ...VOICE_RULES.map((v) => `  - ${v}`));
  return lines.join("\n");
}
